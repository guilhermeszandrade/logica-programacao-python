"""Escreva um algoritimo para ler as dimensoes de um retangulo (base e altura),
calcular e mostrar a area do retangulo. """

base = float(input("Digite o valor da base do retangulo: "))
altura = float(("Digite o valor da altura do retangulo: "))

areaRetangulo = base * altura

print("A area do retangulo e igual a: "+ str(areaRetangulo))